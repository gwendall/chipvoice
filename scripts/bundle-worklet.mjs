import fs from 'node:fs';

/**
 * Inlines the worklet source into a TypeScript module.
 *
 * `audioWorklet.addModule` takes a URL, so a library that ships the worklet as
 * a file makes every consumer copy it into their own public directory and keep
 * the copy in step. Inlining it and handing the browser a blob URL removes that
 * step entirely: `npm install` is the whole setup.
 *
 * The source stays a real .js file so it can be edited, linted and read. This
 * turns it into a string at build time.
 */
const src = fs.readFileSync('src/worklet-source.js', 'utf8');

if (src.includes('`') || src.includes('${')) {
  console.error('The worklet source contains a backtick or a template hole.');
  console.error('It is embedded in a template literal, so both break the build.');
  process.exit(1);
}

fs.writeFileSync(
  'src/worklet-inline.ts',
  `// Generated by scripts/bundle-worklet.mjs. Do not edit.\n` +
    `// Source of truth: src/worklet-source.js\n` +
    `export const WORKLET_SOURCE = \`${src}\`;\n`,
);

console.log(`inlined ${src.length} bytes into src/worklet-inline.ts`);
