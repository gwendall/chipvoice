import assert from 'node:assert/strict';
import { build } from '../../packages/chipvoice/node_modules/esbuild/lib/main.js';
const bundled = await build({ entryPoints: ['src/studio/recording.ts'], bundle: true, platform: 'node', format: 'esm', write: false, logLevel: 'silent' });
const { recordStep } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`);
const first = { bass: 'C2 . . .', lead: 'E4 . G4 .', chord: 'C3 . D3 .', perc: 'K . H .', chordShape: [[0,4,7],[0,3,7]] };
const second = { ...first, lead: 'A4 . B4 .' };
const song = { title: 'Keep the whole score', chip: 'snes', bpm: 120, patterns: [first,second], order: [0,1,0], intent: { lead: 'bright' }, author: 'test' };
const frozen = structuredClone(song);
const lead = recordStep(song, 'lead', 'C5', {step:1,orderIndex:1});
assert.equal(lead.patterns[1].lead, 'A4 C5 B4 .');
assert.equal(lead.patterns[0], first);
assert.deepEqual({ ...lead.patterns[1], lead: second.lead }, second);
assert.deepEqual({ ...lead, patterns: song.patterns }, song);
assert.deepEqual(song, frozen);
assert.equal(recordStep(song, 'lead', 'E4', {step:0,orderIndex:0}), song);
assert.equal(recordStep(song, 'lead', 'C5', {step:99,orderIndex:0}), song);
const drums = recordStep(lead, 'perc', 'S', {step:3,orderIndex:2});
assert.equal(drums.patterns[0].perc, 'K . H S');
assert.equal(drums.patterns[1], lead.patterns[1]);
const chord = recordStep(song, 'chord', 'G3', {step:1,orderIndex:0});
assert.equal(chord.patterns[0].chord, 'C3 G3 D3 .');
assert.deepEqual(chord.patterns[0].chordShape, [[0,4,7],[0,4,7],[0,3,7]], 'inserted chord preserves later voicings');
assert.deepEqual(recordStep(chord, 'chord', 'E3', {step:2,orderIndex:0}).patterns[0].chordShape, chord.patterns[0].chordShape);
const spareShapes = { ...song, patterns: [{ ...first, chord: 'C3 . . .', chordShape: [[0,4,7],[0,3,7],[0,5,7]] }] };
assert.deepEqual(recordStep(spareShapes, 'chord', 'G3', {step:1,orderIndex:0}).patterns[0].chordShape, [[0,4,7],[0,4,7],[0,3,7],[0,5,7]], 'unused authored voicings are retained too');
console.log('PASS overdubs preserve other roles/patterns, repeated order, chord voicings and document ownership');
