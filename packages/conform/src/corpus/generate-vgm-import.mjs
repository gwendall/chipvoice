import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { recordSong, toVgm } from 'chipvoice';
import { formatLog } from '../log.mjs';
import { vgmToWrites } from '../vgm.mjs';

/**
 * The VGM-import corpus, for the NES 2A03 and the Game Boy DMG.
 *
 * `importVgm` (packages/chipvoice) reads a real .vgm file; this harness only
 * ever scores a register log. So each file here is generated twice: once as
 * a .vgm, through this project's own driver and sequencer and then `toVgm`
 * (round-tripping chipvoice's own exporter, which the VGM-import ticket
 * names as "a good round-trip test" for corpus a rip of a commercial game
 * cannot be); once as the .log this harness reads, by decoding that same
 * .vgm with `vgmToWrites` - the harness's own reader, independent of
 * `importVgm` - so a divergence between the two importers would show up as
 * a score against the oracle, not just agree with each other.
 *
 * Both the .vgm (under source/, with its provenance in manifest.json) and
 * the derived .log are committed: the .vgm is what a real player would open,
 * the .log is what `conform` actually runs.
 */
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'corpus');
const GENERATOR = 'packages/conform/src/corpus/generate-vgm-import.mjs';

const FILES = [
  {
    chip: '2a03',
    name: 'song-demo',
    out: '2a03-vgm',
    seconds: 3,
    song: {
      id: 'vgm-import-demo', bpm: 140, order: [0], gain: 1,
      patterns: [{
        bass: 'D2 . D2 . D2 . D2 . E2 . E2 . E2 . E2 .',
        lead: 'D4 . F4 . G4 . A4 . . . G4 . F4 . D4 .',
        chord: 'D3 . . . . . . . . . . . . . . .',
        chordShape: [[0, 3, 7]],
        perc: 'K . H . S . H . K . H . S . H .',
      }],
      lead: { duty: 2, volume: [15, 13, 11, 10, 9], sustain: true },
      chord: { duty: 1, volume: [8, 7, 6], sustain: true },
      bass: { volume: [14], sustain: true },
    },
  },
  {
    chip: 'dmg',
    name: 'song-demo',
    out: 'dmg-vgm',
    seconds: 3,
    song: {
      id: 'vgm-import-demo', bpm: 140, order: [0], gain: 1,
      patterns: [{
        bass: 'D2 . D2 . D2 . D2 . E2 . E2 . E2 . E2 .',
        lead: 'D4 . F4 . G4 . A4 . . . G4 . F4 . D4 .',
        chord: 'D3 . . . . . . . . . . . . . . .',
        chordShape: [[0, 3, 7]],
        perc: 'K . H . S . H . K . H . S . H .',
      }],
      lead: { duty: 2, volume: [15, 14, 13, 12, 11], sustain: true, vibrato: { depth: 0.15, rate: 7, delay: 5 } },
      chord: { duty: 1, volume: [9, 8, 7], sustain: true },
      bass: { volume: [15], sustain: true },
    },
  },
];

for (const spec of FILES) {
  const outDir = path.join(ROOT, spec.out);
  const sourceDir = path.join(outDir, 'source');
  fs.mkdirSync(sourceDir, { recursive: true });

  const { events, cycles } = recordSong(spec.song, { seconds: spec.seconds, chip: spec.chip });
  const vgmBytes = toVgm(events, cycles, {
    chip: spec.chip,
    title: 'chipvoice VGM-import corpus (self-generated)',
    game: 'chipvoice',
    author: 'chipvoice project',
    notes: `Generated by ${GENERATOR} through recordSong + toVgm, for the VGM-import corpus. No external material.`,
  });
  const vgmPath = path.join(sourceDir, `${spec.name}.vgm`);
  fs.writeFileSync(vgmPath, vgmBytes);
  const sha256 = createHash('sha256').update(vgmBytes).digest('hex');

  const manifestPath = path.join(outDir, 'manifest.json');
  const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : [];
  const filename = `source/${spec.name}.vgm`;
  const entry = {
    chip: spec.chip,
    filename,
    source: GENERATOR,
    licence: 'MIT (chipvoice project; self-generated, no external material)',
    sha256,
    note: `Round-trip export of a short chipvoice-composed song (recordSong + toVgm), ${spec.seconds} s.`,
  };
  const next = [...manifest.filter((e) => e.filename !== filename), entry].sort((a, b) => a.filename.localeCompare(b.filename));
  fs.writeFileSync(manifestPath, JSON.stringify(next, null, 2) + '\n');

  const decoded = vgmToWrites(vgmBytes, spec.chip);
  const text = formatLog(
    {
      name: spec.name,
      chip: spec.chip,
      clock: decoded.clock,
      cycles: decoded.cycles,
      source: `${filename}, decoded by packages/conform/src/vgm.mjs`,
      notes: 'self-generated VGM round trip (recordSong -> toVgm -> vgmToWrites); see manifest.json',
      memory: decoded.memory,
    },
    decoded.writes,
  );
  fs.writeFileSync(path.join(outDir, `${spec.name}.log`), text);
  console.log(`${spec.chip.padEnd(6)} ${spec.name.padEnd(14)} ${String(decoded.writes.length).padStart(6)} writes, ${(decoded.cycles / decoded.clock).toFixed(1)} s, sha256 ${sha256.slice(0, 16)}`);
}
