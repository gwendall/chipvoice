import {build} from 'esbuild';
import {writeFile} from 'node:fs/promises';
const result=await build({entryPoints:['scripts/snes-bank-source.ts'],bundle:true,platform:'node',format:'esm',write:false,logLevel:'silent'});
const {compileFactoryBank}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const {image,metadata}=compileFactoryBank();
const source='// Generated by scripts/build-snes-bank.mjs. Original recipes, no game samples.\n'+
  'export const FACTORY_SAMPLES = '+JSON.stringify(metadata)+';\n'+
  'export const FACTORY_RAM_HEX = '+JSON.stringify(Buffer.from(image).toString('hex'))+';\n';
await writeFile('src/chips/snes/bank-inline.ts',source);
console.log(`SNES factory bank: ${metadata.length} samples, ${image.length} RAM bytes; BRR encoding completed at build time`);
